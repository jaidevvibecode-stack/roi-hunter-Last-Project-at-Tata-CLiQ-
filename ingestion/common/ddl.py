"""
ingestion/common/ddl.py
------------------------
DDL for the schemas this project OWNS (raw_meta, raw_mixpanel, ops), GENERATED from the Pydantic row
models so table shapes can never drift from the code that writes them.

  python -m ingestion.common.ddl --dialect redshift   # prints DDL
  python -m ingestion.common.ddl --dialect postgres   # used by tests / docker smoke stack

Nested JSON (dict/list fields) is stored as JSON *text*; dbt parses it (json_text / action_value macros).
Never run automatically against a client warehouse — see RedshiftLoader.bootstrap_owned_schemas().
"""
from __future__ import annotations

import argparse
import types
from datetime import date, datetime
from decimal import Decimal
from typing import Any, Union, get_args, get_origin

from pydantic import BaseModel

from ingestion.common.models import (
    RawAdInsightRow,
    RawAdProductInsightRow,
    RawAdSnapshotRow,
    RawCatalogProductRow,
    RawMixpanelEventRow,
)

TABLES: dict[str, type[BaseModel]] = {
    "raw_meta.ad_insights_daily": RawAdInsightRow,
    "raw_meta.ad_product_insights_daily": RawAdProductInsightRow,
    "raw_meta.catalog_products": RawCatalogProductRow,
    "raw_meta.ads_snapshot": RawAdSnapshotRow,
    "raw_mixpanel.events": RawMixpanelEventRow,
}

# Static ops tables: (column, type) — same types work in Redshift and Postgres.
OPS_TABLES: dict[str, list[tuple[str, str]]] = {
    "ops.ingestion_runs": [
        ("run_id", "VARCHAR(64)"), ("source", "VARCHAR(64)"), ("started_at", "TIMESTAMP"),
        ("finished_at", "TIMESTAMP"), ("status", "VARCHAR(32)"), ("date_from", "DATE"),
        ("date_to", "DATE"), ("rows_loaded", "BIGINT"), ("error", "VARCHAR(65535)"),
    ],
    "ops.ingestion_checkpoints": [
        ("source", "VARCHAR(64)"), ("account_id", "VARCHAR(64)"), ("chunk_key", "VARCHAR(256)"),
        ("date", "DATE"), ("status", "VARCHAR(32)"), ("updated_at", "TIMESTAMP"),
    ],
    "ops.dq_results": [
        ("check_name", "VARCHAR(128)"), ("run_at", "TIMESTAMP"), ("status", "VARCHAR(32)"),
        ("observed", "DOUBLE PRECISION"), ("threshold", "DOUBLE PRECISION"), ("details", "VARCHAR(65535)"),
    ],
}

_TEXT = "VARCHAR(65535)"


def _unwrap(tp: Any) -> Any:
    origin = get_origin(tp)
    if origin in (Union, types.UnionType):
        non_none = [a for a in get_args(tp) if a is not type(None)]
        return _unwrap(non_none[0]) if non_none else str
    return tp


def sql_type(tp: Any) -> str:
    tp = _unwrap(tp)
    if get_origin(tp) in (dict, list) or tp in (dict, list):
        return _TEXT  # JSON text
    if tp is bool:
        return "BOOLEAN"
    if tp is int:
        return "BIGINT"
    if tp in (float, Decimal):
        return "DOUBLE PRECISION"  # raw layer; dbt casts to DECIMAL(18,6)
    if tp is datetime:
        return "TIMESTAMP"
    if tp is date:
        return "DATE"
    if isinstance(tp, type) and issubclass(tp, str):
        return _TEXT
    return _TEXT


_SHORT = ("_id", "level", "status", "source", "currency", "availability", "api_version", "run_id", "event")


def columns_for(model: type[BaseModel]) -> list[tuple[str, str]]:
    cols = []
    for name, f in model.model_fields.items():
        t = sql_type(f.annotation)
        if t == _TEXT and (name == "id" or name.endswith(_SHORT)):
            t = "VARCHAR(256)"  # keep identifier-like columns narrow (wide VARCHARs hurt Redshift memory)
        cols.append((name, t))
    return cols


def generate_ddl(dialect: str = "redshift") -> str:
    if dialect not in ("redshift", "postgres"):
        raise ValueError(dialect)
    out: list[str] = ["-- GENERATED by ingestion/common/ddl.py — do not edit by hand."]
    for schema in ("raw_meta", "raw_mixpanel", "ops"):
        out.append(f"CREATE SCHEMA IF NOT EXISTS {schema};")
    tables = {t: columns_for(m) for t, m in TABLES.items()} | OPS_TABLES
    for table, cols in tables.items():
        body = ",\n  ".join(f'"{c}" {t}' for c, t in cols)
        out.append(f"CREATE TABLE IF NOT EXISTS {table} (\n  {body}\n);")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dialect", default="redshift", choices=["redshift", "postgres"])
    print(generate_ddl(ap.parse_args().dialect))
